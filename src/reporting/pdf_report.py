"""PDF report generation for orcSONAR (Stage 7).

Converts the self-contained HTML report generated by ``html_report`` to a
print-quality PDF using WeasyPrint.  The HTML file is used as the source so
that relative resource paths (images, icons) are resolved against the HTML
file's parent directory.

Academic output format: letter/A4 page with print-friendly CSS media rules.
"""

from __future__ import annotations

from pathlib import Path

from loguru import logger


def generate_pdf_report(html_path: str, output_path: str) -> None:
    """Convert a rendered HTML report to PDF.

    Reads the HTML file at *html_path* and writes a PDF to *output_path*.
    The HTML file's parent directory is used as the base URL so that any
    relative CSS or image references resolve correctly.

    Args:
        html_path: Path to an existing ``.html`` file produced by
            ``html_report.generate_html_report``.
        output_path: Destination path for the ``.pdf`` file.  Parent
            directories are created as needed.

    Raises:
        FileNotFoundError: If *html_path* does not exist.
        RuntimeError: If WeasyPrint fails to generate the PDF.
    """
    from weasyprint import HTML  # deferred import — optional system dependency

    src = Path(html_path).resolve()
    if not src.exists():
        raise FileNotFoundError(f"pdf_report: HTML source not found: {src}")

    dest = Path(output_path)
    dest.parent.mkdir(parents=True, exist_ok=True)

    logger.info(f"pdf_report: rendering {src.name} → {dest.name} …")
    try:
        HTML(filename=str(src), base_url=str(src.parent)).write_pdf(str(dest))
    except Exception as exc:
        raise RuntimeError(f"pdf_report: WeasyPrint failed — {exc}") from exc

    size_kb = dest.stat().st_size / 1024
    logger.info(f"pdf_report: saved → {dest} ({size_kb:.1f} KB)")
